知识库可直接读取 `.md` 和 `.txt` 文件；角色卡还支持 `.json` 和 `.png`，并可批量导入。普通资料会按你当前的问题、最近对话和课堂主题检索少量相关片段，而不是把所有文件粗暴塞入提示词；点击文件可查看全文，长按可删除。

